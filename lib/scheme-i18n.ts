/** Format individual match reasons into the active language */
export function formatReason(reason: string, lang: Language): string {
  if (lang === 'en') return reason;

  // 1. Partial screening note
  if (reason.startsWith('Partial screening only:')) {
    const templates: Record<Language, string> = {
      en: reason,
      hi: 'केवल आंशिक पात्रता जांच: कुछ नियम और अतिरिक्त शर्तें आधिकारिक प्रदाता से जांचें।',
      te: 'పాక్షిక స్క్రీనింగ్ మాత్రమే: అదనపు నిబంధనలను అధికారిక ప్రదాతతో ధృవీకరించుకోండి.',
      mr: 'केवळ प्राथमिक तपासणी: अतिरिक्त अटी आणि नियम अधिकृत प्रदात्याकडून तपासा.',
      ta: 'பகுதி திரையிடல் மட்டுமே: கூடுதல் விதிகளை அதிகாரப்பூர்வ தளத்தில் சரிபார்க்கவும்.',
      kn: 'ಭಾಗಶಃ ತಪಾಸಣೆ ಮಾತ್ರ: ಹೆಚ್ಚುವರಿ ಷರತ್ತುಗಳನ್ನು ಅಧಿಕೃತ ಮೂಲದಿಂದ ಪರಿಶೀಲಿಸಿ.',
      bn: 'কেবলমাত্র আংশিক যাচাই: অতিরিক্ত শর্তাবলী অফিসিয়াল পোর্টাল থেকে যাচাই করুন।',
      gu: 'માત્ર આંશિક તપાસ: વધારાની શરતો સત્તાવાર પોર્ટલ પરથી ચકાસો.',
      pa: 'ਸਿਰਫ਼ ਅੰਸ਼ਕ ਜਾਂਚ: ਵਾਧੂ ਸ਼ਰਤਾਂ ਅਧਿਕਾਰਤ ਪੋਰਟਲ ਤੋਂ ਜਾਂਚੋ।',
    };
    return templates[lang] ?? templates.hi;
  }

  // 2. Policy verification note
  if (reason.startsWith('Policy has not been fully verified')) {
    const templates: Record<Language, string> = {
      en: reason,
      hi: 'नीति की पूर्ण समीक्षा अभी लंबित है; आधिकारिक पोर्टल पर वर्तमान शर्तें जांचें।',
      te: 'విధానం ఇంకా పూర్తిగా ధృవీకరించబడలేదు; అధికారిక పోర్టల్‌లో తాజా నిబంధనలు చూడండి.',
      mr: 'धोरण पूर्णपणे पडताळलेले नाही; अधिकृत पोर्टलवर वर्तमान अटी तपासा.',
      ta: 'கொள்கை முழுமையாக சரிபார்க்கப்படவில்லை; அதிகாரப்பூர்வ இணையதளத்தில் சரிபார்க்கவும்.',
      kn: 'ನೀತಿಯನ್ನು ಸಂಪೂರ್ಣವಾಗಿ ಪರಿಶೀಲಿಸಲಾಗಿಲ್ಲ; ಅಧಿಕೃತ ಪೋರ್ಟಲ್‌ನಲ್ಲಿ ನಿಯಮಗಳನ್ನು ಖಚಿತಪಡಿಸಿ.',
      bn: 'নীতিটি পুরোপুরি যাচাই করা হয়নি; অফিসিয়াল সাইটে বর্তমান শর্তাবলী নিশ্চিত করুন।',
      gu: 'નીતિ સંપૂર્ણપણે ચકાસાયેલ નથી; સત્તાવાર પોર્ટલ પર વર્તમાન શરતો તપાસો.',
      pa: 'ਨੀਤੀ ਪੂਰੀ ਤਰ੍ਹਾਂ ਤਸਦੀਕ ਨਹੀਂ ਹੋਈ; ਅਧਿਕਾਰਤ ਪੋਰਟਲ ਤੋਂ ਮੌਜੂਦਾ ਸ਼ਰਤਾਂ ਜਾਂਚੋ।',
    };
    return templates[lang] ?? templates.hi;
  }

  // 3. Meets modeled rule
  const meetsMatch = reason.match(/^Meets modeled rule:\s*([a-zA-Z]+)\s+([a-z]+)\s+(.+)\.$/);
  if (meetsMatch) {
    const [, field, op, val] = meetsMatch;
    const fLabel = fieldLabels[lang]?.[field] ?? fieldLabels.en[field] ?? field;
    const opSym = opSymbols[op] ?? op;
    const cleanVal = val.replace(/^"|"$/g, '');
    const valLabel = valueLabels[lang]?.[cleanVal] ?? cleanVal;

    const templates: Record<Language, string> = {
      en: reason,
      hi: `मॉडल नियम पूरा: ${fLabel} ${opSym} ${valLabel}`,
      te: `నమూనా నియమం నెరవేరింది: ${fLabel} ${opSym} ${valLabel}`,
      mr: `नियम पूर्ण झाला: ${fLabel} ${opSym} ${valLabel}`,
      ta: `மாதிரி விதி பூர்த்தியானது: ${fLabel} ${opSym} ${valLabel}`,
      kn: `ಮಾದರಿ ನಿಯಮ ಪೂರ್ಣ: ${fLabel} ${opSym} ${valLabel}`,
      bn: `নিয়ম পূরণ হয়েছে: ${fLabel} ${opSym} ${valLabel}`,
      gu: `નિયમ પૂર્ણ થયો: ${fLabel} ${opSym} ${valLabel}`,
      pa: `ਨਿਯਮ ਪੂਰਾ ਹੋਇਆ: ${fLabel} ${opSym} ${valLabel}`,
    };
    return templates[lang] ?? templates.hi;
  }

  // 4. Does not meet modeled rule
  const failsMatch = reason.match(/^Does not meet modeled rule:\s*([a-zA-Z]+)\s+([a-z]+)\s+(.+)\.$/);
  if (failsMatch) {
    const [, field, op, val] = failsMatch;
    const fLabel = fieldLabels[lang]?.[field] ?? fieldLabels.en[field] ?? field;
    const opSym = opSymbols[op] ?? op;
    const cleanVal = val.replace(/^"|"$/g, '');
    const valLabel = valueLabels[lang]?.[cleanVal] ?? cleanVal;

    const templates: Record<Language, string> = {
      en: reason,
      hi: `नियम पूरा नहीं हुआ: ${fLabel} ${opSym} ${valLabel}`,
      te: `నమూనా నియమం సరిపోలలేదు: ${fLabel} ${opSym} ${valLabel}`,
      mr: `नियम पूर्ण होत नाही: ${fLabel} ${opSym} ${valLabel}`,
      ta: `மாதிரி விதி பூர்த்தியாகவில்லை: ${fLabel} ${opSym} ${valLabel}`,
      kn: `ಮಾದರಿ ನಿಯಮ ಹೊಂದಿಲ್ಲ: ${fLabel} ${opSym} ${valLabel}`,
      bn: `নিয়ম পূরণ হয়নি: ${fLabel} ${opSym} ${valLabel}`,
      gu: `નિયમ પૂર્ણ થતો નથી: ${fLabel} ${opSym} ${valLabel}`,
      pa: `ਨਿਯਮ ਪੂਰਾ ਨਹੀਂ ਹੋਇਆ: ${fLabel} ${opSym} ${valLabel}`,
    };
    return templates[lang] ?? templates.hi;
  }

  // 5. Unknown field
  const unknownMatch = reason.match(/^Unknown\s+([a-zA-Z]+):/);
  if (unknownMatch) {
    const field = unknownMatch[1];
    const fLabel = fieldLabels[lang]?.[field] ?? fieldLabels.en[field] ?? field;
    const templates: Record<Language, string> = {
      en: reason,
      hi: `अज्ञात जानकारी (${fLabel}): जांच के लिए यह विवरण आवश्यक है`,
      te: `తెలియని సమాచారం (${fLabel}): పరిశీలనకు ఈ వివరాలు అవసరం`,
      mr: `माहिती उपलब्ध नाही (${fLabel}): तपासणीसाठी आवश्यक`,
      ta: `தெரியாத விவரம் (${fLabel}): சரிபார்க்க தேவை`,
      kn: `ತಿಳಿಯದ ಮಾಹಿತಿ (${fLabel}): ಪರಿಶೀಲನೆಗೆ ಅಗತ್ಯ`,
      bn: `অজানা তথ্য (${fLabel}): যাচাই করতে প্রয়োজন`,
      gu: `અજાણી માહિતી (${fLabel}): ચકાસણી માટે જરૂરી`,
      pa: `ਅਣਜਾਣ ਜਾਣਕਾਰੀ (${fLabel}): ਜਾਂਚ ਲਈ ਲੋੜੀਂਦੀ ਹੈ`,
    };
    return templates[lang] ?? templates.hi;
  }

  return reason;
}

