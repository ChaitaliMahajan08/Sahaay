/** Get the localized version of a scheme, with fallback to English */
export function getLocalizedScheme(scheme: Scheme, lang: Language): Scheme {
  if (lang === 'en') return scheme;

  const translation = schemeLocales[lang]?.[scheme.id] ?? hiSchemes[scheme.id];
  if (!translation) return scheme;

  return {
    ...scheme,
    name: translation.name ?? scheme.name,
    description: translation.description ?? scheme.description,
    benefit: translation.benefit ?? scheme.benefit,
    documents: translation.documents ?? scheme.documents,
    steps: translation.steps ?? scheme.steps,
  };
}
